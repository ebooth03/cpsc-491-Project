"""
OpenAPI schema snapshot test (KAN-72).

The frontend is built against the API's request and response shapes.
This test compares the schema FastAPI generates today with a committed
snapshot (snapshots/openapi.json), so any change to an endpoint, field,
type or validation rule fails CI until the snapshot is updated in the
same pull request. That makes every contract change visible in review.

The snapshot detects contract changes; it does not prove the API is
correct. Correctness is covered by the API and validation tests.

To accept an intentional change, regenerate the snapshot from backend/:

    UPDATE_OPENAPI_SNAPSHOT=1 python -m pytest tests/test_openapi_snapshot.py

then commit the updated snapshots/openapi.json with your change.
"""

import copy
import difflib
import json
import os
from pathlib import Path

import pytest

from app.main import app


SNAPSHOT_PATH = Path(__file__).parent / "snapshots" / "openapi.json"
UPDATE_ENV_VAR = "UPDATE_OPENAPI_SNAPSHOT"

SCAN_ENDPOINTS = {
    "/scans": {"get", "post"},
    "/scans/{scan_id}": {"get"},
    "/scans/{scan_id}/status": {"get"},
    "/scans/{scan_id}/results": {"get"},
}


def render(schema: dict) -> str:
    """Serialize a schema the same way every time so diffs are stable."""
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


def current_schema() -> dict:
    # Round-trip through JSON so the comparison uses exactly what a
    # client would download from /openapi.json.
    return json.loads(json.dumps(app.openapi()))


def load_snapshot(path: Path = SNAPSHOT_PATH) -> dict:
    if not path.exists():
        pytest.fail(
            f"Missing OpenAPI snapshot at {path}. Generate it with "
            f"{UPDATE_ENV_VAR}=1 python -m pytest "
            "tests/test_openapi_snapshot.py",
            pytrace=False,
        )
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        pytest.fail(
            f"The OpenAPI snapshot at {path} is not valid JSON "
            f"({error}). Regenerate it with {UPDATE_ENV_VAR}=1 "
            "python -m pytest tests/test_openapi_snapshot.py",
            pytrace=False,
        )


def snapshot_mismatch(snapshot: dict, schema: dict) -> str | None:
    """
    Return a failure message with a unified diff if the schemas differ,
    or None if they match.
    """
    if schema == snapshot:
        return None

    diff = "".join(
        difflib.unified_diff(
            render(snapshot).splitlines(keepends=True),
            render(schema).splitlines(keepends=True),
            fromfile="snapshots/openapi.json (committed)",
            tofile="generated by app.openapi() (current code)",
            n=2,
        )
    )
    return (
        "The API schema no longer matches the committed snapshot.\n"
        "If this change is intentional, regenerate the snapshot with\n"
        f"  {UPDATE_ENV_VAR}=1 python -m pytest "
        "tests/test_openapi_snapshot.py\n"
        "and commit it in the same PR so reviewers see the contract "
        "change.\n\n" + diff
    )


def test_openapi_schema_matches_committed_snapshot():
    schema = current_schema()

    if os.environ.get(UPDATE_ENV_VAR) == "1":
        SNAPSHOT_PATH.parent.mkdir(parents=True, exist_ok=True)
        SNAPSHOT_PATH.write_text(render(schema), encoding="utf-8")
        return

    message = snapshot_mismatch(load_snapshot(), schema)
    if message:
        pytest.fail(message, pytrace=False)


def test_served_schema_matches_generated_schema(client):
    """/openapi.json is what the frontend and Swagger UI actually load."""
    response = client.get("/openapi.json")

    assert response.status_code == 200
    assert response.json() == current_schema()


def test_snapshot_documents_every_scan_endpoint():
    """Guards against committing an empty or truncated snapshot."""
    paths = load_snapshot()["paths"]

    for path, methods in SCAN_ENDPOINTS.items():
        assert path in paths, f"{path} missing from snapshot"
        assert methods <= set(paths[path]), (
            f"{path} snapshot is missing methods "
            f"{sorted(methods - set(paths[path]))}"
        )


def test_snapshot_records_shared_contract_models():
    schemas = load_snapshot()["components"]["schemas"]

    for model in (
        "ScanConfiguration",
        "PortRange",
        "ScanResult",
        "HostResult",
        "PortResult",
        "ScanStatus",
        "VulnerabilityFinding",
    ):
        assert model in schemas, f"{model} missing from snapshot"


def test_snapshot_matches_itself():
    snapshot = load_snapshot()

    assert snapshot_mismatch(snapshot, snapshot) is None


def test_removed_response_field_fails_with_readable_diff():
    """
    Proves the comparison catches a real breaking change and that the
    failure explains it: removing a response field the frontend reads
    must produce a diff naming the field and the update instructions.
    """
    snapshot = load_snapshot()
    changed = copy.deepcopy(snapshot)
    del changed["components"]["schemas"]["ScanStatus"]["properties"][
        "progress_percent"
    ]

    message = snapshot_mismatch(snapshot, changed)

    assert message is not None
    assert "--- snapshots/openapi.json (committed)" in message
    assert "+++ generated by app.openapi() (current code)" in message
    assert '-          "progress_percent": {' in message
    assert f"{UPDATE_ENV_VAR}=1" in message


def test_corrupted_snapshot_reports_clear_error(tmp_path):
    broken = tmp_path / "openapi.json"
    broken.write_text("{ not valid json", encoding="utf-8")

    with pytest.raises(pytest.fail.Exception, match="not valid JSON"):
        load_snapshot(broken)


def test_missing_snapshot_explains_how_to_generate_it(tmp_path):
    with pytest.raises(pytest.fail.Exception, match=UPDATE_ENV_VAR):
        load_snapshot(tmp_path / "missing.json")
